#!/usr/bin/env python3
"""Generate the go2rtc and Frigate configs from the camera inventory.

cameras.yaml is the only file people edit. The two generated files are
committed, so reviewers can see exactly what runs on the gateway, and
`--check` fails when they are out of date with the inventory.

Secrets never appear in the output. Camera credentials are written as
${CAMxx_USER} / ${CAMxx_PASSWORD} (expanded by go2rtc from its environment),
and Frigate reads go2rtc with {FRIGATE_GO2RTC_RTSP_USER} placeholders
(expanded by Frigate). Both come from /etc/vivo/secrets.env.

usage:
  tools/gen_config.py                 # write go2rtc/go2rtc.yaml and frigate/config.yml
  tools/gen_config.py --check         # exit 1 if the committed files are stale
  tools/gen_config.py --inventory cameras.lab.yaml --out /tmp/lab
"""
import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# GENERATED by tools/gen_config.py from {src}. Do not edit by hand.\n"
ID_RE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
CRED_RE = re.compile(r"^[A-Z][A-Z0-9_]{0,31}$")
AUDIO_PRESETS = {
    "aac": "preset-record-generic-audio-aac",    # transcode audio to AAC (MP4 cannot hold G.711)
    "copy": "preset-record-generic-audio-copy",  # camera already sends AAC
    "none": "preset-record-generic",             # drop audio
}
REQUIRED = ("id", "name", "host", "main_path", "sub_path", "credentials")


class InventoryError(ValueError):
    pass


def load_inventory(path: Path) -> dict:
    data = yaml.safe_load(path.read_text())
    if not isinstance(data, dict) or not isinstance(data.get("cameras"), list) or not data["cameras"]:
        raise InventoryError(f"{path}: needs a non-empty 'cameras' list")
    site = data.get("site") or {}
    seen = set()
    for i, cam in enumerate(data["cameras"], 1):
        where = f"{path}: camera #{i}"
        missing = [k for k in REQUIRED if not cam.get(k)]
        if missing:
            raise InventoryError(f"{where}: missing {', '.join(missing)}")
        if not ID_RE.match(cam["id"]):
            raise InventoryError(f"{where}: id '{cam['id']}' must match {ID_RE.pattern}")
        if cam["id"] in seen:
            raise InventoryError(f"{where}: duplicate id '{cam['id']}'")
        seen.add(cam["id"])
        if not CRED_RE.match(cam["credentials"]):
            raise InventoryError(f"{where}: credentials '{cam['credentials']}' must match {CRED_RE.pattern}")
        for key in ("main_path", "sub_path"):
            if not str(cam[key]).startswith("/"):
                raise InventoryError(f"{where}: {key} must start with /")
        cam.setdefault("port", 554)
        cam.setdefault("audio", "aac")
        if cam["audio"] not in AUDIO_PRESETS:
            raise InventoryError(f"{where}: audio must be one of {', '.join(AUDIO_PRESETS)}")
    site.setdefault("record_days", 7)
    site.setdefault("hwaccel", "preset-vaapi")
    site.setdefault("detect", {"width": 640, "height": 360, "fps": 5})
    data["site"] = site
    return data


def camera_url(cam: dict, path_key: str) -> str:
    c = cam["credentials"]
    return f"rtsp://${{{c}_USER}}:${{{c}_PASSWORD}}@{cam['host']}:{cam['port']}{cam[path_key]}"


def restream_url(stream: str) -> str:
    # Frigate expands {FRIGATE_*} placeholders in input paths at startup.
    return (
        "rtsp://{FRIGATE_GO2RTC_RTSP_USER}:{FRIGATE_GO2RTC_RTSP_PASSWORD}"
        f"@go2rtc:8554/{stream}"
    )


def build_go2rtc(inv: dict) -> dict:
    streams = {}
    for cam in inv["cameras"]:
        streams[f"{cam['id']}_main"] = [camera_url(cam, "main_path")]
        streams[f"{cam['id']}_sub"] = [camera_url(cam, "sub_path")]
    return {
        "api": {
            "listen": ":1984",
            "username": "${GO2RTC_API_USER}",
            "password": "${GO2RTC_API_PASSWORD}",
        },
        "rtsp": {
            "listen": ":8554",
            "username": "${FRIGATE_GO2RTC_RTSP_USER}",
            "password": "${FRIGATE_GO2RTC_RTSP_PASSWORD}",
        },
        "webrtc": {
            "listen": ":8555",
            "candidates": ["${GATEWAY_LAN_IP}:8555"],
        },
        "log": {"format": "text", "level": "info"},
        "streams": streams,
    }


def build_frigate(inv: dict) -> dict:
    site = inv["site"]
    cameras = {}
    for cam in inv["cameras"]:
        cameras[cam["id"]] = {
            "friendly_name": cam["name"],
            "ffmpeg": {
                "inputs": [
                    {
                        "path": restream_url(f"{cam['id']}_main"),
                        "input_args": "preset-rtsp-restream",
                        "roles": ["record"],
                    },
                    {
                        "path": restream_url(f"{cam['id']}_sub"),
                        "input_args": "preset-rtsp-restream",
                        "roles": ["detect"],
                    },
                ],
                "output_args": {"record": AUDIO_PRESETS[cam["audio"]]},
            },
        }
    return {
        "version": "0.18-0",
        "mqtt": {"enabled": False},
        "telemetry": {"version_check": False},
        "birdseye": {"enabled": False},
        "audio": {"enabled": False},
        "semantic_search": {"enabled": False},
        "face_recognition": {"enabled": False},
        "lpr": {"enabled": False},
        "snapshots": {"enabled": False},
        # hwaccel: none (lab hosts without an Intel GPU) leaves Frigate on CPU decoding.
        **({} if str(site["hwaccel"]).lower() in ("none", "") else {"ffmpeg": {"hwaccel_args": site["hwaccel"]}}),
        "detect": {
            "enabled": False,
            "width": site["detect"]["width"],
            "height": site["detect"]["height"],
            "fps": site["detect"]["fps"],
        },
        "record": {
            "enabled": True,
            "continuous": {"days": site["record_days"]},
            "motion": {"days": 0},
        },
        "cameras": cameras,
    }


GO2RTC_NOTES = """\
# go2rtc pulls each camera stream once and shares it with Frigate, the live
# view and (later) the substream archiver. ${VAR} values come from
# /etc/vivo/secrets.env and /etc/vivo/site.env at container start.
"""

FRIGATE_NOTES = """\
# Frigate records each camera's main stream continuously from go2rtc.
# Detection, snapshots, audio events, Birdseye and all AI features are off.
# The detect input (substream) is still decoded at low resolution because
# Frigate needs it for motion and stats; decoding uses Intel VAAPI.
# The file is mounted read-only, so settings cannot be changed in the UI.
"""


def render(data: dict, src: str, notes: str) -> str:
    body = yaml.safe_dump(data, sort_keys=False, default_flow_style=False, width=200)
    return HEADER.format(src=src) + notes + "\n" + body


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--inventory", default=str(ROOT / "cameras.yaml"))
    ap.add_argument("--out", default=str(ROOT), help="directory that holds go2rtc/ and frigate/")
    ap.add_argument("--check", action="store_true", help="fail if generated files differ from what is on disk")
    args = ap.parse_args()

    inv_path = Path(args.inventory)
    try:
        inv = load_inventory(inv_path)
    except (InventoryError, yaml.YAMLError) as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 2

    out = Path(args.out)
    targets = {
        out / "go2rtc" / "go2rtc.yaml": render(build_go2rtc(inv), inv_path.name, GO2RTC_NOTES),
        out / "frigate" / "config.yml": render(build_frigate(inv), inv_path.name, FRIGATE_NOTES),
    }

    if args.check:
        stale = [str(p) for p, text in targets.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("STALE: run tools/gen_config.py and commit:\n  " + "\n  ".join(stale), file=sys.stderr)
            return 1
        print(f"OK: generated configs match {inv_path.name} ({len(inv['cameras'])} cameras)")
        return 0

    for path, text in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
